-- ============================================
-- ZeroSum - Initial Database Schema
-- Flyway Migration V1
-- ============================================


-- ============================================
-- 1. USERS
-- ============================================

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) UNIQUE,
    password_hash VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ============================================
-- 2. GROUPS
-- ============================================

CREATE TABLE groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,

    group_type VARCHAR(20) NOT NULL,

    join_code VARCHAR(20) NOT NULL UNIQUE,

    created_by BIGINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_groups_created_by
        FOREIGN KEY (created_by)
        REFERENCES users(id),

    CONSTRAINT chk_groups_group_type
        CHECK (group_type IN ('general', 'hostel', 'trip'))
);


-- ============================================
-- 3. GROUP MEMBERS
-- ============================================

CREATE TABLE group_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    group_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,

    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_group_members_group
        FOREIGN KEY (group_id)
        REFERENCES groups(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_group_members_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),

    CONSTRAINT uq_group_members_group_user
        UNIQUE (group_id, user_id)
);


-- ============================================
-- 4. EXPENSES
-- ============================================

CREATE TABLE expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    group_id BIGINT NOT NULL,
    paid_by BIGINT NOT NULL,

    description VARCHAR(255) NOT NULL,

    -- Money is stored in paise
    amount_paise BIGINT NOT NULL,

    category VARCHAR(100),

    expense_date DATE NOT NULL,

    is_recurring BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_expenses_group
        FOREIGN KEY (group_id)
        REFERENCES groups(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_expenses_paid_by
        FOREIGN KEY (paid_by)
        REFERENCES users(id),

    CONSTRAINT chk_expenses_amount
        CHECK (amount_paise > 0)
);


-- ============================================
-- 5. EXPENSE SHARES
-- ============================================

CREATE TABLE expense_shares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    expense_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,

    -- Money is stored in paise
    share_amount_paise BIGINT NOT NULL,

    share_type VARCHAR(20) NOT NULL,

    participated BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_expense_shares_expense
        FOREIGN KEY (expense_id)
        REFERENCES expenses(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_expense_shares_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),

    CONSTRAINT uq_expense_shares_expense_user
        UNIQUE (expense_id, user_id),

    CONSTRAINT chk_expense_shares_amount
        CHECK (share_amount_paise >= 0),

    CONSTRAINT chk_expense_shares_type
        CHECK (
            share_type IN (
                'equal',
                'percentage',
                'exact',
                'shares'
            )
        )
);


-- ============================================
-- 6. SETTLEMENT RUNS
-- ============================================

CREATE TABLE settlement_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    group_id BIGINT NOT NULL,

    run_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    raw_transaction_count INT NOT NULL,

    optimized_transaction_count INT NOT NULL,

    explanation_json JSONB,

    CONSTRAINT fk_settlement_runs_group
        FOREIGN KEY (group_id)
        REFERENCES groups(id)
        ON DELETE CASCADE
);


-- ============================================
-- 7. SETTLEMENTS
-- ============================================

CREATE TABLE settlements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    group_id BIGINT NOT NULL,

    from_user BIGINT NOT NULL,
    to_user BIGINT NOT NULL,

    -- Money is stored in paise
    amount_paise BIGINT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'pending',

    settled_at TIMESTAMPTZ,

    CONSTRAINT fk_settlements_group
        FOREIGN KEY (group_id)
        REFERENCES groups(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_settlements_from_user
        FOREIGN KEY (from_user)
        REFERENCES users(id),

    CONSTRAINT fk_settlements_to_user
        FOREIGN KEY (to_user)
        REFERENCES users(id),

    CONSTRAINT chk_settlements_amount
        CHECK (amount_paise > 0),

    CONSTRAINT chk_settlements_status
        CHECK (status IN ('pending', 'completed')),

    CONSTRAINT chk_settlements_different_users
        CHECK (from_user <> to_user)
);


-- ============================================
-- 8. RECURRING RULES
-- ============================================

CREATE TABLE recurring_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    group_id BIGINT NOT NULL,

    description VARCHAR(255) NOT NULL,

    -- Money is stored in paise
    amount_paise BIGINT NOT NULL,

    category VARCHAR(100),

    frequency VARCHAR(50) NOT NULL,

    next_run_date DATE NOT NULL,

    CONSTRAINT fk_recurring_rules_group
        FOREIGN KEY (group_id)
        REFERENCES groups(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_recurring_rules_amount
        CHECK (amount_paise > 0)
);


-- ============================================
-- 9. IOUs
-- ============================================

CREATE TABLE ious (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    from_user BIGINT NOT NULL,
    to_user BIGINT NOT NULL,

    -- Money is stored in paise
    amount_paise BIGINT NOT NULL,

    note VARCHAR(255),

    group_id BIGINT,

    settled BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ious_from_user
        FOREIGN KEY (from_user)
        REFERENCES users(id),

    CONSTRAINT fk_ious_to_user
        FOREIGN KEY (to_user)
        REFERENCES users(id),

    CONSTRAINT fk_ious_group
        FOREIGN KEY (group_id)
        REFERENCES groups(id)
        ON DELETE SET NULL,

    CONSTRAINT chk_ious_amount
        CHECK (amount_paise > 0),

    CONSTRAINT chk_ious_different_users
        CHECK (from_user <> to_user)
);


-- ============================================
-- INDEXES
-- ============================================

CREATE INDEX idx_group_members_group_id
    ON group_members(group_id);

CREATE INDEX idx_group_members_user_id
    ON group_members(user_id);

CREATE INDEX idx_expenses_group_id
    ON expenses(group_id);

CREATE INDEX idx_expenses_paid_by
    ON expenses(paid_by);

CREATE INDEX idx_expense_shares_expense_id
    ON expense_shares(expense_id);

CREATE INDEX idx_expense_shares_user_id
    ON expense_shares(user_id);

CREATE INDEX idx_settlement_runs_group_id
    ON settlement_runs(group_id);

CREATE INDEX idx_settlements_group_id
    ON settlements(group_id);

CREATE INDEX idx_ious_group_id
    ON ious(group_id);

CREATE INDEX idx_ious_from_user
    ON ious(from_user);

CREATE INDEX idx_ious_to_user
    ON ious(to_user);